CREATE TABLE transfers (
    id UUID PRIMARY KEY,
    source_account_id BIGINT NOT NULL REFERENCES accounts (id),
    destination_account VARCHAR(32) NOT NULL,
    destination_bank VARCHAR(16) NOT NULL DEFAULT 'HORIZONTE' CHECK (destination_bank = 'HORIZONTE'),
    amount NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    currency CHAR(3) NOT NULL DEFAULT 'AOA' CHECK (currency = 'AOA'),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts (id),
    transfer_id UUID NOT NULL UNIQUE REFERENCES transfers (id),
    type VARCHAR(6) NOT NULL DEFAULT 'DEBIT' CHECK (type = 'DEBIT'),
    amount NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
